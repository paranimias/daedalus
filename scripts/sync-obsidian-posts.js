#!/usr/bin/env node
/*
 * Sync plain, single-language notes from an Obsidian vault into the
 * bilingual `_posts/*.md` format this Jekyll theme expects.
 *
 * Why this exists
 * ----------------
 * The theme's multilingual posts are a single file with both languages
 * wrapped in `<div class="es/en post-container" markdown="1">` and a JS
 * toggle. That's fine for Jekyll but awful to *write*: Obsidian doesn't
 * understand kramdown's `markdown="1"`, so it renders those divs as
 * literal HTML instead of formatted text, and a single note holding two
 * languages breaks most of what makes Obsidian pleasant (front matter
 * per note, spellcheck, etc).
 *
 * So the vault keeps two plain folders of ordinary single-language notes,
 * and this script merges matching pairs into the dual-<div> post format
 * on its way into `_posts/`. The generated files are build output —
 * treat the vault as the source of truth and re-run this script instead
 * of hand-editing anything under `_posts/` that carries the marker
 * comment below.
 *
 * Vault layout expected (folder pointed to by $OBSIDIAN_BLOG_DIR):
 *
 *   es/
 *     hola.md          <- canonical: title, date, tags, author, etc.
 *   en/
 *     hola.md          <- only `title` and `subtitle` are read (become
 *                          `en_title` / `en_subtitle`);
 *                          everything else in this file is ignored.
 *
 * Pairing is by identical filename between es/ and en/. A note that only
 * exists in es/ is published as a normal (non-multilingual) post — you
 * don't need the translation ready to publish. A note that only exists
 * in en/ is skipped with a warning: es/ is always canonical for
 * title/date/tags/etc.
 *
 * A note with `in-progress: true` in its front matter (or an `in-progress`
 * tag) is written to Jekyll's own `_drafts/` instead of `_posts/` — it
 * won't show up on `jekyll serve`/`build` unless you pass `--drafts`, and
 * it doesn't need a `date:` yet. If only the en/ note is in-progress, the
 * es/ one still publishes normally on its own — the translation just
 * isn't linked in.
 *
 * Usage:
 *   OBSIDIAN_BLOG_DIR=~/Documentos/obsidian/vault/blog npm run sync:obsidian
 *   OBSIDIAN_BLOG_DIR=~/Documentos/obsidian/vault/blog npm run sync:obsidian:watch
 *
 * Images: put them in `$OBSIDIAN_BLOG_DIR/img/` (subfolders welcome, e.g.
 * `img/mi-post/portada.webp`). Notes can reference them as `![[portada.webp]]`,
 * `![[mi-post/portada.webp]]` or `![alt](../img/mi-post/portada.webp)`, and
 * `header-img: mi-post/portada.webp` works in front matter. On sync they're
 * copied to `img/posts/` in this repo and the links rewritten to
 * `/img/posts/...`. Only `img/` is searched (not the vault's attachments
 * folder); a missing image is reported and its link left untouched.
 *
 * Flags:
 *   --watch   keep running, re-sync on any change under es/ or en/
 *   --force   overwrite a target file even if it wasn't generated by
 *             this script (normally refused, to avoid clobbering
 *             hand-written posts)
 */

const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const REPO_ROOT = path.resolve(__dirname, '..');
const POSTS_DIR = path.join(REPO_ROOT, '_posts');
const DRAFTS_DIR = path.join(REPO_ROOT, '_drafts');
const IMG_DEST_DIR = path.join(REPO_ROOT, 'img', 'posts');
const MARKER_PREFIX = '<!-- AUTO-GENERATED from Obsidian vault';

const args = process.argv.slice(2);
const WATCH = args.includes('--watch');
const FORCE = args.includes('--force');

function fail(msg) {
  console.error(`\x1b[31merror:\x1b[0m ${msg}`);
  process.exit(1);
}

const vaultDir = process.env.OBSIDIAN_BLOG_DIR;
if (!vaultDir) {
  fail(
    'OBSIDIAN_BLOG_DIR is not set. Point it at the vault folder that ' +
      'contains your es/ and en/ note folders, e.g.\n' +
      '  OBSIDIAN_BLOG_DIR=~/Vault/Blog npm run sync:obsidian'
  );
}
const imgDir = path.join(vaultDir, 'img');
const esDir = path.join(vaultDir, 'es');
const enDir = path.join(vaultDir, 'en');
if (!fs.existsSync(esDir)) {
  fail(`Can't find ${esDir} — expected an "es" folder inside OBSIDIAN_BLOG_DIR.`);
}

function slugify(str) {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // strip accents (combining diacritical marks)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function toDateOnly(d) {
  const date = d instanceof Date ? d : new Date(d);
  if (isNaN(date.getTime())) {
    fail(`Invalid \`date:\` value: ${d}`);
  }
  return date.toISOString().slice(0, 10);
}

function listMdFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.toLowerCase().endsWith('.md'))
    .sort();
}

function readNote(dir, filename) {
  const raw = fs.readFileSync(path.join(dir, filename), 'utf8');
  return matter(raw);
}

// --- Images ---------------------------------------------------------------

function listFilesRecursive(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? listFilesRecursive(full) : [full];
  });
}

// Find an image inside the vault's img/ folder from whatever the note wrote:
// "foo.png", "sub/foo.png", "img/sub/foo.png", "../img/sub/foo.png". Falls
// back to a unique-by-basename match (Obsidian wikilink behavior).
// Returns the path relative to img/ (posix separators), or null.
function resolveImage(ref) {
  let rel = ref;
  try {
    rel = decodeURIComponent(ref);
  } catch (e) {
    // keep as-is
  }
  rel = rel.replace(/\\/g, '/').replace(/^(\.\.?\/)+/, '').replace(/^img\//, '');
  if (!rel || rel.split('/').includes('..')) return null;
  if (fs.existsSync(path.join(imgDir, rel)) && fs.statSync(path.join(imgDir, rel)).isFile()) {
    return rel;
  }
  const base = path.basename(rel);
  const matches = listFilesRecursive(imgDir).filter((f) => path.basename(f) === base);
  return matches.length === 1 ? path.relative(imgDir, matches[0]).split(path.sep).join('/') : null;
}

function copyImage(rel) {
  const src = path.join(imgDir, rel);
  const dest = path.join(IMG_DEST_DIR, rel);
  const srcStat = fs.statSync(src);
  if (fs.existsSync(dest)) {
    const destStat = fs.statSync(dest);
    if (destStat.size === srcStat.size && destStat.mtimeMs >= srcStat.mtimeMs) return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
  fs.utimesSync(dest, srcStat.atime, srcStat.mtime);
}

const encodePath = (rel) => rel.split('/').map(encodeURIComponent).join('/');

// Rewrite local image references in a note body (skipping fenced code
// blocks) to /img/posts/..., copying the files over. `label` is only used
// in warnings.
function processImages(content, label) {
  const handle = (ref) => {
    const rel = resolveImage(ref);
    if (!rel) {
      console.warn(`warn: ${label} — image not found in img/: ${ref}`);
      return null;
    }
    copyImage(rel);
    return `/img/posts/${encodePath(rel)}`;
  };

  return content
    .split(/(```[\s\S]*?```)/)
    .map((chunk, i) => {
      if (i % 2 === 1) return chunk; // fenced code block
      return chunk
        // ![[file.png]] / ![[file.png|alt or width]]
        .replace(/!\[\[([^\]|]+?)(?:\|([^\]]*))?\]\]/g, (m, target, alias) => {
          const url = handle(target.trim());
          if (!url) return m;
          const alt = alias && !/^\d+(x\d+)?$/.test(alias.trim()) ? alias.trim() : '';
          return `![${alt}](${url})`;
        })
        // ![alt](local/path.png "title")
        .replace(/!\[([^\]]*)\]\(([^)\s]+)((?:\s+"[^"]*")?)\)/g, (m, alt, ref, title) => {
          if (/^([a-z][a-z0-9+.-]*:|\/|#)/i.test(ref)) return m; // URL / absolute
          const url = handle(ref);
          return url ? `![${alt}](${url}${title})` : m;
        });
    })
    .join('');
}

// A note is "in progress" if it has `in-progress: true` in front matter, or
// carries an `in-progress` tag — whichever is more natural to reach for in
// Obsidian. Either way, it's not ready to publish yet.
function isInProgress(data) {
  if (data['in-progress']) return true;
  if (Array.isArray(data.tags)) {
    return data.tags.map(String).includes('in-progress');
  }
  return false;
}

function sync() {
  const esFiles = listMdFiles(esDir);
  const enFiles = new Set(listMdFiles(enDir));

  if (esFiles.length === 0) {
    console.log('Nothing to do: no notes found in', esDir);
    return;
  }

  const seenSlugs = new Set();
  let written = 0;
  let skipped = 0;

  for (const filename of esFiles) {
    const basename = filename.replace(/\.md$/i, '');
    const es = readNote(esDir, filename);
    const isDraft = isInProgress(es.data);

    if (!es.data.title) {
      console.warn(`skip: es/${filename} has no \`title\` in front matter`);
      skipped++;
      continue;
    }
    if (!isDraft && !es.data.date) {
      console.warn(`skip: es/${filename} has no \`date\` in front matter (drafts don't need one)`);
      skipped++;
      continue;
    }

    let hasTranslation = enFiles.has(filename);
    let en = hasTranslation ? readNote(enDir, filename) : null;
    if (hasTranslation) enFiles.delete(filename);
    // When es/ is itself a draft, keep the in-progress translation so the
    // bilingual draft can be previewed.
    if (en && isInProgress(en.data) && !isDraft) {
      console.log(`note: en/${filename} is in-progress — publishing/drafting es/${filename} without it`);
      hasTranslation = false;
      en = null;
    }

    const dateOnly = es.data.date ? toDateOnly(es.data.date) : null;
    const slug = es.data.slug ? slugify(String(es.data.slug)) : slugify(basename);
    if (seenSlugs.has(slug)) {
      console.warn(`skip: es/${filename} — slug "${slug}" collides with another note`);
      skipped++;
      continue;
    }
    seenSlugs.add(slug);

    const frontMatter = { ...es.data };
    delete frontMatter.slug;
    delete frontMatter['in-progress'];
    if (Array.isArray(frontMatter.tags)) {
      frontMatter.tags = frontMatter.tags.filter((t) => String(t) !== 'in-progress');
    }
    if (typeof frontMatter['header-img'] === 'string') {
      // A cover that lives in the vault's img/ gets copied; anything else
      // (e.g. an existing repo asset like img/cat-home-bg.webp) is left alone.
      const headerRel = resolveImage(frontMatter['header-img']);
      if (headerRel) {
        copyImage(headerRel);
        frontMatter['header-img'] = `img/posts/${headerRel}`;
      }
    }
    if (dateOnly) frontMatter.date = dateOnly; // plain YYYY-MM-DD, not a full ISO timestamp
    frontMatter.layout = 'post';
    if (hasTranslation) {
      frontMatter.multilingual = true;
      frontMatter.en_title = en.data.title || es.data.title;
      if (en.data.subtitle) frontMatter.en_subtitle = en.data.subtitle;
    }

    const body = hasTranslation
      ? [
          '<!-- Spanish Version -->',
          '<div class="es post-container" markdown="1">',
          processImages(es.content.trim(), `es/${filename}`),
          '</div>',
          '',
          '<!-- English Version -->',
          '<div class="en post-container" markdown="1">',
          processImages(en.content.trim(), `en/${filename}`),
          '</div>',
          '',
        ].join('\n')
      : processImages(es.content.trim(), `es/${filename}`) + '\n';

    const marker = `${MARKER_PREFIX} (es/${filename}${hasTranslation ? `, en/${filename}` : ''}) — do not edit directly, edit the vault note and run \`npm run sync:obsidian\` again. -->`;

    // Drafts go to Jekyll's own _drafts/ (undated filename, only built with
    // `jekyll serve/build --drafts`); finished posts go to _posts/ as usual.
    const targetDir = isDraft ? DRAFTS_DIR : POSTS_DIR;
    const outName = isDraft ? `${slug}.md` : `${dateOnly}-${slug}.md`;
    const outFile = path.join(targetDir, outName);
    const outContent = matter.stringify(body, frontMatter) + '\n' + marker + '\n';

    if (fs.existsSync(outFile) && !FORCE) {
      const existing = fs.readFileSync(outFile, 'utf8');
      if (!existing.includes(MARKER_PREFIX)) {
        console.warn(
          `skip: ${path.relative(REPO_ROOT, outFile)} already exists and wasn't ` +
            'generated by this script (no marker found). Use --force to overwrite it anyway.'
        );
        skipped++;
        continue;
      }
    }

    fs.mkdirSync(targetDir, { recursive: true });
    fs.writeFileSync(outFile, outContent);
    console.log(
      `wrote: ${path.relative(REPO_ROOT, outFile)}${hasTranslation ? ' (es+en)' : ' (es only)'}${isDraft ? ' [draft]' : ''}`
    );
    written++;
  }

  for (const leftover of enFiles) {
    console.warn(`skip: en/${leftover} has no matching es/${leftover} — es/ is canonical, add it there too`);
    skipped++;
  }

  console.log(`Done: ${written} written, ${skipped} skipped.`);
}

sync();

if (WATCH) {
  console.log(`\nWatching ${esDir} and ${enDir} for changes... (Ctrl+C to stop)`);
  let timer = null;
  const debouncedSync = () => {
    clearTimeout(timer);
    timer = setTimeout(sync, 300);
  };
  for (const dir of [esDir, enDir]) {
    if (fs.existsSync(dir)) fs.watch(dir, debouncedSync);
  }
  if (fs.existsSync(imgDir)) {
    try {
      fs.watch(imgDir, { recursive: true }, debouncedSync);
    } catch (e) {
      fs.watch(imgDir, debouncedSync); // no recursive support: top level only
    }
  }
}
